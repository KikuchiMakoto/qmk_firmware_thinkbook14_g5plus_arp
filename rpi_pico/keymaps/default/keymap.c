#include QMK_KEYBOARD_H

enum layers {
    _BASE = 0,
    _FN,
    _FNLOCK,
    _FNLOCK_FN,
};

enum custom_keycodes {
    FN_LOCK = QK_USER_0,
};

static bool fn_lock_active = false;

static void update_fn_lock_led(bool active) {
#ifdef LED_FN_LOCK_PIN
    gpio_write_pin(LED_FN_LOCK_PIN, active ? LED_PIN_ON_STATE : !LED_PIN_ON_STATE);
#endif
}

void keyboard_post_init_user(void) {
#ifdef LED_FN_LOCK_PIN
    gpio_set_pin_output(LED_FN_LOCK_PIN);
#endif
    update_fn_lock_led(fn_lock_active);
}

bool process_record_user(uint16_t keycode, keyrecord_t *record) {
    switch (keycode) {
        case FN_LOCK:
            if (record->event.pressed) {
                fn_lock_active = !fn_lock_active;
                default_layer_set((layer_state_t)1 << (fn_lock_active ? _FNLOCK : _BASE));
                update_fn_lock_led(fn_lock_active);
            }
            return false;
        default:
            return true;
    }
}

